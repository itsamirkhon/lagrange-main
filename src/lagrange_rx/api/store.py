"""Read approved graphs from persistent state, with a read-only synthetic demo fallback.

The synthetic fixture is generated by scripts/prepare_demo.py at release-build time,
stored under demo/graphs/, and never uploaded or passed off as customer evidence.
Real committed graphs remain in the configured data root and always take precedence.
"""
from __future__ import annotations

import json
from pathlib import Path

from lagrange_rx.ontology import ClientGraph


_BUNDLED_DEMO_GRAPHS = Path(__file__).resolve().parents[3] / "demo" / "graphs"


class GraphStore:
    def __init__(self, root: Path):
        self.dir = Path(root) / 'graphs'

    def ids(self) -> list[str]:
        ids: set[str] = set()
        if self.dir.is_dir():
            ids.update(p.stem for p in self.dir.glob('*.json') if p.stem.isalnum())
        if _BUNDLED_DEMO_GRAPHS.is_dir():
            ids.update(
                p.stem for p in _BUNDLED_DEMO_GRAPHS.glob('demo*.json')
                if p.stem.isalnum()
            )
        return sorted(ids)

    def get(self, graph_id: str) -> ClientGraph | None:
        if not graph_id.isalnum():  # blocks traversal; batch ids are hex
            return None
        path = self.dir / (graph_id + '.json')
        if not path.is_file() and graph_id.startswith("demo"):
            path = _BUNDLED_DEMO_GRAPHS / (graph_id + ".json")
        if not path.is_file():
            return None
        return ClientGraph.model_validate(json.loads(path.read_text(encoding='utf-8')))
